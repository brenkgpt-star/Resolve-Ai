// Match free text intelligently
export function matchFreeText(text) {
  const t = text.toLowerCase()
  if (t.includes('chuveiro') || t.includes('água quente') || t.includes('agua quente') || t.includes('banho') || t.includes('resistência') || t.includes('resistencia')) {
    return 'chuveiro'
  }
  if (t.includes('torneira') || t.includes('vazando') || t.includes('vazamento') || t.includes('pingando') || t.includes('pinga') || t.includes('gota')) {
    return 'torneira'
  }
  if (t.includes('sifão') || t.includes('sifao') || t.includes('pia') || t.includes('ralo') || t.includes('esgoto') || t.includes('entupida') || t.includes('entupido')) {
    return 'sifao'
  }
  if (t.includes('tomada') || t.includes('disjuntor') || t.includes('energia') || t.includes('luz') || t.includes('curto') || t.includes('interruptor') || t.includes('fiação')) {
    return 'tomada'
  }
  if (t.includes('porta') || t.includes('dobradiça') || t.includes('dobradica') || t.includes('range') || t.includes('fechadura') || t.includes('emperrada') || t.includes('trinco')) {
    return 'porta'
  }
  return 'outro'
}

